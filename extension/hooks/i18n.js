export function actionLabel(action){return action==='file.write' || action==='bash.command'?t('action.'+action):t('rule.'+action);}

let language = 'en';

// 'auto' follows the LANG-style locale passed in; anything unknown is English.
export function setLanguage(value, locale = '') {
  const chosen = value === 'vi' || value === 'en' ? value : /^vi(?:[_.-]|$)/i.test(String(locale)) ? 'vi' : 'en';
  language = chosen;
  return language;
}

export function currentLanguage() { return language; }

export function t(key, values = {}) {
  const template = TEXT[language][key] ?? TEXT.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ''));
}

export function ruleLabel(rule) {
  return rule.source === 'builtin' ? t(`rule.${rule.id}`) : `${rule.action} · ${rule.target}`;
}
